#!/usr/bin/env python3
"""Generate send-admission-b-echo.toml, Experiment B's uncontended run.

One server guest on hv02 and one client guest on hv01 run every cell, so the
arms are compared within one boot.

Cells: one discarded warm-up cell, then ROUNDS rounds of the arms, the order
rotated each round. Each cell starts its own server on port 7900+k,
runs a closed-loop window and an open-loop window, each between barriers, and
stops the server. The server-side sampler step of each window has its own
rezolus recording.

    python3 experiments/send-admission-b-echo-gen.py > experiments/send-admission-b-echo.toml
    python3 experiments/send-admission-b-echo-gen.py controls > experiments/send-admission-b-echo-controls.toml

`controls` adds two arms that separate what bytes-admitted-timeout changes:
bytes-admitted-await (the same await of settlement, without the timers) and
bytes-nowait with --defer-recv-arm (the receive armed after the response is
sent, which BENCHMARKS.md found cheaper in closed loop).
"""

import sys

# label -> (bench-server --echo-mode, extra bench-server flags)
ARMS = {
    "bytes-nowait": ("bytes-nowait", ""),
    "bytes-admitted": ("bytes-admitted", ""),
    "bytes-admitted-timeout": ("bytes-admitted-timeout", ""),
}
CONTROLS = {
    "bytes-admitted-await": ("bytes-admitted-await", ""),
    "bytes-nowait-defer": ("bytes-nowait", " --defer-recv-arm"),
}
ROUNDS = 4


def cells(arms):
    labels = list(arms)
    out = [("warmup", labels[0])]
    for r in range(ROUNDS):
        order = labels[r % len(labels):] + labels[: r % len(labels)]
        out += [(f"rep{r + 1}", arm) for arm in order]
    return out


HEADER = '''# Experiment B, uncontended (docs/send-admission-design.md, section 4): what
# send_admitted costs a saturated worker against send_nowait.
# Generated by send-admission-b-echo-gen.py; edit that.
#
# Server guest on hv02 (z1, 24 vCPU), bench-server with ONE worker, pinned by
# ringline to CPU 0. Client guest on hv01 (z2, 56 vCPU), {client_threads}
# threads. The X710 LAG between them, {msg_size} B messages, {clients}
# connections.
#
# Arms (label: bench-server --echo-mode and flags):
#   bytes-nowait            with_bytes, then send_nowait
#   bytes-admitted          with_bytes, then send_admitted, completion dropped
#   bytes-admitted-timeout  with_bytes, then section 2's example: send_admitted
#                           under timeout(1 s), then the completion under
#                           timeout(1 s)
ARMS_EXTRA#
# Cells: CELLS_LINE
# Each cell runs its own server on port 7900+k and two windows:
#   closed  one request in flight per connection, which saturates the worker.
#           Statistic: the worker thread's CPU time per operation, from
#           /proc/<pid>/task/<tid>/schedstat over the window (warm-up + 1 s
#           to the end - 1 s), divided by the client's operations.
#   open    {open_rate} requests/s offered, about half the closed-loop rate.
#           Statistic: the client's p99, measured from each request's
#           scheduled send time.
name = "send-admission B echo NAME{run}"

[params]
bins_artifact  = "REPLACE-WITH-ARTIFACT-ID"
run            = "1"
image          = "debian-13-6.12"
server_ip      = "172.31.0.1"
client_ip      = "172.31.0.2"
client_threads = "16"
clients        = "256"
msg_size       = "256"
warmup         = "5"
duration       = "20"
open_rate      = "55000"
'''

SERVER_START = '''
# -- server: hv02 --------------------------------------------------------------

[[jobs]]
name = "server"
tags = ["z1.baremetal"]

[[jobs.steps]]
type = "anvil-vm"
mode = "start"
shape = "z1.c"
image = "{image}"
gpu = false
data_address = "{server_ip}/24"
boot_timeout = 600

[[jobs.steps]]
type = "anvil-vm"
mode = "exec"
inputs = [{ artifact = "{bins_artifact}", name = "bench-bins.tgz", dest = "/home/anvil" }]
payload = \'\'\'
set -uo pipefail
cd /home/anvil && tar xzf bench-bins.tgz && chmod +x out/* || exit 1
mkdir -p logs
cat /etc/anvil-image.json 2>/dev/null || cat /etc/anvil-instance.json; echo
uname -r; nproc
cat /sys/devices/system/clocksource/clocksource0/current_clocksource
sudo sysctl -w net.core.somaxconn=65535 net.ipv4.tcp_max_syn_backlog=65535 net.core.rmem_max=134217728 net.core.wmem_max=134217728
ip -4 -brief addr show
( cd out && sha256sum * )
got=$(./out/bench-server --print-backend)
[ "$got" = io_uring ] || { echo "BACKEND MISMATCH: bench-server is $got"; exit 1; }
echo "run={run} backend=$got"
\'\'\'
'''

SAMPLER = '''pid=$(systemctl show -p MainPID --value srv{k})
tid=$(ps -L -o tid=,comm= -p "$pid" | awk '$2=="rl-work-0" {{print $1}}')
[ -n "$tid" ] || {{ echo "no rl-work-0 thread in pid $pid"; ps -L -o tid,comm,psr -p "$pid"; exit 1; }}
echo "cell={k} tag={tag} arm={arm} window={window} pid=$pid worker_tid=$tid $(grep Cpus_allowed_list /proc/$pid/task/$tid/status | tr -d '\\t')"
sleep $(({{warmup}} + 1))
a=$(cut -d' ' -f1 /proc/$pid/task/$tid/schedstat); t0=$(date +%s%N)
sleep $(({{duration}} - 2))
b=$(cut -d' ' -f1 /proc/$pid/task/$tid/schedstat); t1=$(date +%s%N)
echo "WORKER cell={k} tag={tag} arm={arm} window={window} cpu_ns=$((b - a)) wall_ns=$((t1 - t0))"'''


def server_cell(k, tag, arm, arms):
    port = 7900 + k
    mode, flags = arms[arm]
    out = f'''
# cell {k}: {tag} {arm}
[[jobs.steps]]
type = "anvil-vm"
mode = "exec"
detach = true
unit = "srv{k}"
payload = "exec /home/anvil/out/bench-server --runtime ringline --echo-mode {mode}{flags} --addr {{server_ip}}:{port} --workers 1 --msg-size {{msg_size}} > /home/anvil/logs/srv{k}-{arm}.log 2>&1"
'''
    for window in ("closed", "open"):
        out += f'''
[[jobs.steps]]
type = "barrier"
name = "ready{k}-{window}"
timeout = 1800

[[jobs.steps]]
type = "anvil-vm"
mode = "exec"
metrics = true
upload = true
payload = \'\'\'
{SAMPLER.format(k=k, tag=tag, arm=arm, window=window)}
\'\'\'

[[jobs.steps]]
type = "barrier"
name = "done{k}-{window}"
timeout = 1800
'''
    out += f'''
[[jobs.steps]]
type = "anvil-vm"
mode = "exec"
payload = \'\'\'
sudo systemctl kill -s INT srv{k}
for i in $(seq 1 50); do systemctl is-active --quiet srv{k} || break; sleep 0.2; done
ss -ltnH "sport = :{port}" | grep -q . && {{ echo "port {port} still listening"; exit 1; }}
echo "SERVER cell={k} tag={tag} arm={arm} $(grep bytes_send_failed /home/anvil/logs/srv{k}-{arm}.log)"
\'\'\'
'''
    return out


SERVER_END = '''
[[jobs.steps]]
type = "anvil-vm"
mode = "exec"
upload = true
artifacts = ["/home/anvil/logs.tgz"]
payload = \'\'\'
cd /home/anvil && tar czf logs.tgz logs
\'\'\'

[[jobs.steps]]
type = "anvil-vm"
mode = "stop"
'''

CLIENT_START = '''
# -- client: hv01 --------------------------------------------------------------

[[jobs]]
name = "client"
tags = ["z2.baremetal"]

[[jobs.steps]]
type = "anvil-vm"
mode = "start"
shape = "z2.c"
image = "{image}"
gpu = false
data_address = "{client_ip}/24"
boot_timeout = 600

[[jobs.steps]]
type = "anvil-vm"
mode = "exec"
inputs = [{ artifact = "{bins_artifact}", name = "bench-bins.tgz", dest = "/home/anvil" }]
payload = \'\'\'
set -uo pipefail
cd /home/anvil && tar xzf bench-bins.tgz && chmod +x out/* || exit 1
mkdir -p results
cat /etc/anvil-image.json 2>/dev/null || cat /etc/anvil-instance.json; echo
uname -r; nproc
sudo sysctl -w net.core.rmem_max=134217728 net.core.wmem_max=134217728 net.ipv4.ip_local_port_range="1024 65535"
ip -4 -brief addr show
ping -c 2 -W 2 {server_ip} || echo "WARN: server address not reachable yet"
\'\'\'
'''


def client_cell(k, tag, arm):
    port = 7900 + k
    out = ""
    for window, extra in (("closed", ""), ("open", " --open --rate {open_rate}")):
        name = f"c{k}-{tag}-{arm}-{window}"
        wait = (
            f"for i in $(seq 1 100); do (exec 3<>/dev/tcp/{{server_ip}}/{port}) 2>/dev/null && {{ exec 3>&-; break; }}; sleep 0.1; done\n"
            if window == "closed"
            else ""
        )
        out += f'''
# cell {k}: {tag} {arm} {window}
[[jobs.steps]]
type = "barrier"
name = "ready{k}-{window}"
timeout = 1800

[[jobs.steps]]
type = "anvil-vm"
mode = "exec"
payload = \'\'\'
cd /home/anvil
ulimit -n 500000
{wait}./out/bench-client --runtime ringline --addr {{server_ip}}:{port} --clients {{clients}} --msg-size {{msg_size}} --threads {{client_threads}} --warmup {{warmup}} --duration {{duration}}{extra} > results/{name}.json 2> results/{name}.log
echo "CELL k={k} tag={tag} arm={arm} window={window} rc=$? $(tail -1 results/{name}.log)"
exit 0
\'\'\'

[[jobs.steps]]
type = "barrier"
name = "done{k}-{window}"
timeout = 1800
'''
    return out


def client_end(n):
    return f'''
[[jobs.steps]]
type = "anvil-vm"
mode = "exec"
upload = true
artifacts = ["/home/anvil/results.tgz"]
payload = \'\'\'
cd /home/anvil && tar czf results.tgz results
n=$(ls results/*.json | wc -l); echo "RESULT windows=$n expected={n}"
[ "$n" = {n} ]
\'\'\'

[[jobs.steps]]
type = "anvil-vm"
mode = "stop"
'''


def main():
    controls = sys.argv[1:] == ["controls"]
    arms = dict(ARMS, **CONTROLS) if controls else ARMS
    cs = cells(arms)
    line = ", ".join(f"{k}={tag}:{arm}" for k, (tag, arm) in enumerate(cs))
    extra = (
        "#   bytes-admitted-await    with_bytes, then send_admitted, then the\n"
        "#                           completion awaited with no timeout\n"
        "#   bytes-nowait-defer      bytes-nowait with --defer-recv-arm\n"
        if controls
        else ""
    )
    header = (
        HEADER.replace("CELLS_LINE", line)
        .replace("ARMS_EXTRA", extra)
        .replace("NAME", "controls" if controls else "rounds")
    )
    out = [header, SERVER_START]
    out += [server_cell(k, tag, arm, arms) for k, (tag, arm) in enumerate(cs)]
    out += [SERVER_END, CLIENT_START]
    out += [client_cell(k, tag, arm) for k, (tag, arm) in enumerate(cs)]
    out.append(client_end(2 * len(cs)))
    print("".join(out), end="")


if __name__ == "__main__":
    main()
